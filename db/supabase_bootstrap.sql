-- Izlek database bootstrap for a brand-new Supabase PostgreSQL project.
-- This mirrors the current Rails migrations and records them as applied so
-- that a later `bin/rails db:migrate` does not try to recreate these tables.
-- Run once in Supabase SQL Editor against an empty database. Do not use this
-- to overwrite an existing database.

BEGIN;

CREATE TABLE public.organizations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name character varying NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_address character varying NOT NULL,
  password_digest character varying NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL,
  name character varying DEFAULT '' NOT NULL,
  role character varying DEFAULT 'requester' NOT NULL,
  organization_id bigint
);

CREATE TABLE public.tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_name character varying NOT NULL,
  requester_email character varying NOT NULL,
  subject character varying NOT NULL,
  description text NOT NULL,
  status character varying DEFAULT 'new' NOT NULL,
  priority character varying DEFAULT 'normal' NOT NULL,
  assignee character varying,
  first_response_at timestamp(6) without time zone,
  solved_at timestamp(6) without time zone,
  response_due_at timestamp(6) without time zone NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL,
  organization_id bigint,
  requester_user_id bigint,
  assignee_user_id bigint
);

CREATE TABLE public.replies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL,
  author_name character varying NOT NULL,
  body text NOT NULL,
  internal boolean DEFAULT false NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL,
  user_id bigint
);

CREATE TABLE public.sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  ip_address character varying,
  user_agent character varying,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL
);

CREATE UNIQUE INDEX index_users_on_email_address
  ON public.users (email_address);
CREATE INDEX index_users_on_organization_id
  ON public.users (organization_id);
CREATE INDEX index_tickets_on_status
  ON public.tickets (status);
CREATE INDEX index_tickets_on_response_due_at
  ON public.tickets (response_due_at);
CREATE INDEX index_tickets_on_organization_id
  ON public.tickets (organization_id);
CREATE INDEX index_tickets_on_requester_user_id
  ON public.tickets (requester_user_id);
CREATE INDEX index_tickets_on_assignee_user_id
  ON public.tickets (assignee_user_id);
CREATE INDEX index_replies_on_ticket_id
  ON public.replies (ticket_id);
CREATE INDEX index_replies_on_user_id
  ON public.replies (user_id);
CREATE INDEX index_sessions_on_user_id
  ON public.sessions (user_id);

ALTER TABLE public.users
  ADD CONSTRAINT fk_users_organization
  FOREIGN KEY (organization_id) REFERENCES public.organizations (id);
ALTER TABLE public.tickets
  ADD CONSTRAINT fk_tickets_organization
  FOREIGN KEY (organization_id) REFERENCES public.organizations (id);
ALTER TABLE public.tickets
  ADD CONSTRAINT fk_tickets_requester_user
  FOREIGN KEY (requester_user_id) REFERENCES public.users (id);
ALTER TABLE public.tickets
  ADD CONSTRAINT fk_tickets_assignee_user
  FOREIGN KEY (assignee_user_id) REFERENCES public.users (id);
ALTER TABLE public.replies
  ADD CONSTRAINT fk_replies_ticket
  FOREIGN KEY (ticket_id) REFERENCES public.tickets (id);
ALTER TABLE public.replies
  ADD CONSTRAINT fk_replies_user
  FOREIGN KEY (user_id) REFERENCES public.users (id);
ALTER TABLE public.sessions
  ADD CONSTRAINT fk_sessions_user
  FOREIGN KEY (user_id) REFERENCES public.users (id);

-- Rails migration tracking. These are the five versions currently in db/migrate.
CREATE TABLE public.schema_migrations (
  version character varying NOT NULL PRIMARY KEY
);
INSERT INTO public.schema_migrations (version) VALUES
  ('20261016130000'),
  ('20261016130100'),
  ('20261016130101'),
  ('20261016130102'),
  ('20261016130300');

-- Mark the database as production for Rails' environment safety check.
CREATE TABLE public.ar_internal_metadata (
  key character varying NOT NULL PRIMARY KEY,
  value character varying,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL
);
INSERT INTO public.ar_internal_metadata (key, value, created_at, updated_at)
VALUES ('environment', 'production', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

COMMIT;
